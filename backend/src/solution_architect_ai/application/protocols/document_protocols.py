from collections.abc import AsyncIterator
from dataclasses import dataclass
from typing import Protocol
from uuid import UUID

from solution_architect_ai.application.models.document_dto import (
    DocumentVersionView,
    DocumentView,
    StoredParse,
    UploadDocument,
    UploadOperationView,
)
from solution_architect_ai.domain.documents import ParsedDocument


@dataclass(frozen=True)
class StagedFile:
    temporary_key: str
    size: int
    sha256: str


class FileStorage(Protocol):
    async def stage(self, chunks: AsyncIterator[bytes]) -> StagedFile: ...
    async def staged_content(self, staged_file: StagedFile) -> bytes: ...
    async def discard(self, staged_file: StagedFile) -> None: ...
    async def publish(self, staged_file: StagedFile, storage_key: str) -> None: ...
    async def read(self, storage_key: str, size: int, digest: str) -> bytes: ...


class DocumentParser(Protocol):
    def validate(self, content: bytes, filename: str, mime_type: str) -> str: ...
    def parse(
        self, file_id: UUID, version_id: UUID, content: bytes, filename: str, mime_type: str
    ) -> ParsedDocument: ...


class DocumentStore(Protocol):
    async def list_documents(self) -> list[DocumentView]: ...
    async def list_versions(self, file_id: UUID) -> list[DocumentVersionView]: ...
    async def get_version(self, version_id: UUID) -> DocumentVersionView: ...
    async def prepare(
        self, command: UploadDocument, size: int, digest: str, payload_digest: str
    ) -> UploadOperationView: ...
    async def complete(self, operation_id: UUID) -> DocumentVersionView: ...
    async def pending(self) -> list[UploadOperationView]: ...
    async def get_upload_operation(self, operation_id: UUID) -> UploadOperationView: ...
    async def get_parse(self, version_id: UUID) -> StoredParse | None: ...
    async def save_parse(self, parsed: StoredParse) -> StoredParse: ...
    async def attach_document(self, message_id: UUID, version_id: UUID) -> DocumentVersionView: ...
    async def list_attachments(self, message_id: UUID) -> list[DocumentVersionView]: ...
